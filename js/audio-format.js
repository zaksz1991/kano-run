export const AUDIO_ASSET_ROOT = '/assets/models/audio/';
export const OPUS_AUDIO_MIME = 'audio/ogg; codecs="opus"';

const SAFE_ASSET_NAME = /^[a-z0-9][a-z0-9._-]*\.(?:mp3|ogg)$/i;

/** Return true only when the browser reports native Ogg/Opus support. */
export function supportsOpusAudio(audioElement) {
  try {
    const answer = String(audioElement?.canPlayType?.(OPUS_AUDIO_MIME) || '').toLowerCase();
    return answer === 'probably' || answer === 'maybe';
  } catch {
    return false;
  }
}

/**
 * Pick an encoded variant only when a successful local compression run
 * registered it and the browser supports Ogg/Opus. Always retain the MP3 URL
 * as a fallback. The registry is generated by scripts/compress-audio.mjs.
 */
export function resolveAudioAsset(filename, variants = {}, opusSupported = false, root = AUDIO_ASSET_ROOT) {
  const name = String(filename || '');
  if (!SAFE_ASSET_NAME.test(name) || name.includes('..')) return null;

  const mp3Url = `${root}${encodeURIComponent(name)}`;
  const variant = variants && typeof variants[name] === 'string' ? variants[name] : '';
  if (opusSupported && variant && SAFE_ASSET_NAME.test(variant) && !variant.includes('..')) {
    return {
      url: `${root}${encodeURIComponent(variant)}`,
      fallbackUrl: mp3Url,
      format: 'opus',
      mp3Url,
    };
  }

  return { url: mp3Url, fallbackUrl: null, format: 'mp3', mp3Url };
}

/**
 * Switch an HTMLAudioElement to its registered MP3 fallback at most once.
 * The function deliberately leaves playback control to its AudioManager.
 */
export function switchToMp3Fallback(player) {
  const fallbackUrl = player?.__kanoAudioFallbackUrl;
  if (!player || !fallbackUrl || player.__kanoAudioFallbackUsed) return false;
  player.__kanoAudioFallbackUsed = true;
  player.__kanoAudioUsingMp3Fallback = true;
  player.__kanoAudioFallbackUrl = null;
  try {
    player.src = fallbackUrl;
    player.load?.();
    return true;
  } catch {
    return false;
  }
}
