class LocalizationManager {
  constructor(options = {}) {
    this.defaultLanguage = options.defaultLanguage || "en";
    this.language = this.defaultLanguage;
    this.translations = {
      ...TRANSLATIONS,
      ...(options.translations || {}),
    };
    this.listeners = new Set();
    this.storageKey = options.storageKey || "kanoRunLanguage";
  }

  init() {
    let savedLanguage = null;

    try {
      savedLanguage = globalThis.localStorage?.getItem(
        this.storageKey
      );
    } catch {
      // Storage may be unavailable.
    }

    if (savedLanguage && this.translations[savedLanguage]) {
      this.setLanguage(savedLanguage, false);
    } else {
      this.setLanguage(this.defaultLanguage, false);
    }

    return this;
  }

  getAvailableLanguages() {
    return Object.keys(this.translations);
  }

  getLanguage() {
    return this.language;
  }

  setLanguage(language, persist = true) {
    if (!this.translations[language]) {
      return false;
    }

    this.language = language;

    if (typeof document !== "undefined") {
      document.documentElement.lang = language;
    }

    if (persist) {
      try {
        globalThis.localStorage?.setItem(
          this.storageKey,
          language
        );
      } catch {
        // Continue without persistence.
      }
    }

    this.notifyListeners();
    return true;
  }

  translate(key, variables = {}) {
    const dictionary =
      this.translations[this.language] ||
      this.translations[this.defaultLanguage] ||
      {};

    let value =
      dictionary[key] ??
      this.translations[this.defaultLanguage]?.[key] ??
      key;

    if (typeof value !== "string") {
      return String(value);
    }

    return value.replace(/\{(\w+)\}/g, (match, name) => {
      return Object.prototype.hasOwnProperty.call(variables, name)
        ? String(variables[name])
        : match;
    });
  }

  t(key, variables = {}) {
    return this.translate(key, variables);
  }

  addTranslations(language, dictionary) {
    if (!language || !dictionary || typeof dictionary !== "object") {
      throw new TypeError(
        "A language code and translation dictionary are required."
      );
    }

    this.translations[language] = {
      ...(this.translations[language] || {}),
      ...dictionary,
    };

    this.notifyListeners();
  }

  subscribe(listener) {
    if (typeof listener !== "function") {
      throw new TypeError(
        "Localization listener must be a function."
      );
    }

    this.listeners.add(listener);

    return () => this.listeners.delete(listener);
  }

  notifyListeners() {
    for (const listener of this.listeners) {
      try {
        listener({
          language: this.language,
          translations: this.translations[this.language],
        });
      } catch (error) {
        console.error("Localization listener failed:", error);
      }
    }
  }

  destroy() {
    this.listeners.clear();
  }
}

export { TRANSLATIONS };
export default LocalizationManager;