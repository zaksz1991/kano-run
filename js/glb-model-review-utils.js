export function cloneJson(value) {
  return JSON.parse(JSON.stringify(value));
}

export function initialOverridesFromReport(report) {
  const categories = {};
  const applied = report?.overrideAudit?.appliedCategories || [];
  for (const category of applied) {
    if (CATALOG_KEYS.includes(category)) categories[category] = [...(report?.catalog?.[category] || [])];
  }
  const exclude = {};
  for (const row of report?.overrideAudit?.appliedExclusions || []) {
    if (!CATALOG_KEYS.includes(row.category) || !row.path) continue;
    if (!exclude[row.category]) exclude[row.category] = [];
    if (!exclude[row.category].includes(row.path)) exclude[row.category].push(row.path);
  }
  return { schemaVersion: 1, description: 'Exact GLB paths selected in Kano Life GLB Visual Review. Paths are relative to public/assets/models/ and must match actual filenames and capitalization.', categories, exclude };
}

export function currentCategoryPaths(report, draft, category) {
  if (Object.prototype.hasOwnProperty.call(draft?.categories || {}, category)) {
    return [...(draft.categories[category] || [])];
  }
  return [...(report?.catalog?.[category] || [])];
}

export function toggleCategoryPath(report, draft, category, relativePath) {
  if (!CATALOG_KEYS.includes(category)) throw new Error(`Unknown category: ${category}`);
  if (typeof relativePath !== 'string' || !relativePath || relativePath.startsWith('/') || relativePath.split('/').includes('..')) {
    throw new Error('The asset path must be a safe relative path.');
  }
  const next = cloneJson(draft || { schemaVersion: 1, categories: {}, exclude: {} });
  if (!Object.prototype.hasOwnProperty.call(next.categories || {}, category)) {
    next.categories ||= {};
    next.categories[category] = [...(report?.catalog?.[category] || [])];
  }
  const paths = next.categories[category];
  const index = paths.indexOf(relativePath);
  const action = index === -1 ? 'added' : 'removed';
  if (index === -1) paths.push(relativePath);
  else paths.splice(index, 1);
  paths.sort((a, b) => a.localeCompare(b));
  return { draft: next, action, paths: [...paths] };
}

export function publicModelUrl(relativePath, base = '/assets/models/') {
  const clean = String(relativePath || '').replace(/^\/+/, '');
  if (!clean || clean.split('/').some((part) => part === '..' || part === '.')) throw new Error('Unsafe model path.');
  return `${base}${clean.split('/').map(encodeURIComponent).join('/')}`;
}

export function createOverridePayload(draft) {
  const categories = {};
  for (const key of CATALOG_KEYS) {
    if (Object.prototype.hasOwnProperty.call(draft?.categories || {}, key)) {
      categories[key] = [...new Set((draft.categories[key] || []).filter((p) => typeof p === 'string'))].sort((a, b) => a.localeCompare(b));
    }
  }
  const exclude = {};
  for (const key of CATALOG_KEYS) {
    const paths = [...new Set((draft?.exclude?.[key] || []).filter((p) => typeof p === 'string'))].sort((a, b) => a.localeCompare(b));
    if (paths.length) exclude[key] = paths;
  }
  return {
    schemaVersion: 1,
    description: 'Generated by Kano Life GLB Visual Review. Paths are exact and relative to public/assets/models/. Review visually before applying.',
    categories,
    exclude,
  };
}

export function currentAssignments(report, draft, filePath) {
  return CATALOG_KEYS.filter((category) => currentCategoryPaths(report, draft, category).includes(filePath));
}

export function classifyFilterMatches(file, filter) {
  if (filter === 'all') return true;
  const categories = new Set(file?.categories || []);
  const p = String(file?.path || '').toLowerCase();
  if (filter === 'unclassified') return !(file?.categories || []).length;
  if (filter === 'buildings') return [...categories].some((key) => ['building', 'industrialBuilding', 'flyover', 'marketStall', 'busStop'].includes(key)) || /world\/(buildings|frontage|shops|market)/.test(p);
  if (filter === 'characters') return [...categories].some((key) => ['passenger', 'passengerWoman', 'passengerMan', 'passengerVIP', 'security', 'pedestrian', 'pedestrianWoman'].includes(key)) || /character|pedestrian|passenger|people|human|person/.test(p);
  if (filter === 'vehicles') return [...categories].some((key) => ['keke', 'car', 'taxi', 'suv', 'truck', 'bus', 'motorcycle', 'police', 'karota', 'ambulance'].includes(key)) || /vehicle|vehicles|keke|car|motorbike|motorcycle|okada/.test(p);
  if (filter === 'environment') return [...categories].some((key) => ['dirtmound', 'roadlight', 'cone', 'bench', 'trafficLight', 'stopSign'].includes(key)) || /environment|ground|road|street|pothole|sand|asphalt/.test(p);
  return true;
}
